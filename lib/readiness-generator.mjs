export function generateAiEntities({ domain, siteName, description, industry = 'Technology' }) {
  return JSON.stringify({
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "version": "1.0.0",
    "generatedBy": "AnswerIndex",
    "canonicalDomain": domain,
    "primaryEntity": {
      "name": siteName,
      "type": "Organization",
      "industry": industry,
      "description": description || `${siteName} digital presence and answer repository.`,
      "url": `https://${domain}`,
      "sameAs": []
    },
    "keyTaxonomies": [
      {
        "category": "Core Offerings",
        "terms": ["Software", "Platform", "API", "Documentation"]
      }
    ],
    "factualClaims": [
      {
        "claim": `${siteName} publishes verified, authoritative answers and machine-readable context.`,
        "sourceUrl": `https://${domain}`
      }
    ]
  }, null, 2);
}

