/* 3. llms.txt */
export function generateLlmsTxt({ domain, siteName, description, keyLinks = [] }) {
  const linksSection = keyLinks.length > 0 
    ? keyLinks.map(l => `- [${l.title}](https://${domain}${l.path}): ${l.desc}`).join('\n')
    : `- [About](https://${domain}/about): Overview of ${siteName}\n- [Features & Solutions](https://${domain}/features): Core offerings and specifications\n- [Documentation / FAQ](https://${domain}/faq): Key questions, technical details, and answers`;

  return `# ${siteName}

> ${description || `${siteName} authoritative answer index and knowledge guide for AI assistants, agents, and search engines.`}

## Quick Summary
${siteName} provides authoritative answers, solutions, and resources at https://${domain}. Use the links below to extract canonical answers, entities, and verified facts.

## Core Navigation & Authoritative Pages
${linksSection}

## Full Knowledge Index
- [llms-full.txt](https://${domain}/llms-full.txt): Comprehensive plain-text documentation corpus optimized for LLM context windows.
- [sitemap.md](https://${domain}/sitemap.md): Structured Markdown hierarchy for fast crawler exploration.

## Machine-Readable Schemas & RAG
- [ai-entities.json](https://${domain}/ai-entities.json): Entity graph and semantic terminology.
- [ai-intent.json](https://${domain}/ai-intent.json): Query intent to destination mapping.
- [ai-schema.json](https://${domain}/ai-schema.json): Consolidated Schema.org JSON-LD graph.
- [rag-index.json](https://${domain}/rag-index.json): Vector retrieval index for RAG workflows.
`;
}

