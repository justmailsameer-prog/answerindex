/* Master Orchestrator */
export function generateAllReadinessFiles({ domain, siteName, description, industry, outDir }) {
  const cleanDomain = domain.replace(/^https?:\/\//, '').replace(/\/.*$/, '').toLowerCase();
  const name = siteName || cleanDomain.split('.')[0].toUpperCase();
  const targetDir = outDir || path.resolve(process.cwd(), 'ai-readiness-dist', cleanDomain);

  if (!fs.existsSync(targetDir)) {
    fs.mkdirSync(targetDir, { recursive: true });
  }

  const wellKnownDir = path.join(targetDir, '.well-known');
  if (!fs.existsSync(wellKnownDir)) {
    fs.mkdirSync(wellKnownDir, { recursive: true });
  }

  const files = {
    // 1. Identity & Permissions
    'robots.txt': generateRobotsTxt({ domain: cleanDomain, siteName: name }),
    'ai.txt': generateAiTxt({ domain: cleanDomain, siteName: name }),
    // 2. Content Files
    'llms.txt': generateLlmsTxt({ domain: cleanDomain, siteName: name, description }),
    'llms-full.txt': generateLlmsFullTxt({ domain: cleanDomain, siteName: name, description }),
    // 3. Map & Navigation
    'sitemap.md': generateSitemapMd({ domain: cleanDomain, siteName: name }),
    'ai-sitemap.xml': generateAiSitemap({ domain: cleanDomain }),
    // 4. Intelligence Files
    'ai-entities.json': generateAiEntities({ domain: cleanDomain, siteName: name, description, industry }),
    'ai-intent.json': generateAiIntent({ domain: cleanDomain, siteName: name }),
    'ai-schema.json': generateAiSchema({ domain: cleanDomain, siteName: name, description }),
    // 5. Research Files (RAG)
    'rag-index.json': generateRagIndexJson({ domain: cleanDomain, siteName: name, description }),
    'rag-index.jsonl': generateRagIndexJsonl({ domain: cleanDomain, siteName: name, description }),
    // 6. Policy & Integrations
    'training-data-policy.txt': generateTrainingPolicy({ domain: cleanDomain, siteName: name }),
    'ai-disclosure.txt': generateAiDisclosure({ siteName: name }),
    '.well-known/ai-plugin.json': generateAiPluginJson({ domain: cleanDomain, siteName: name, description }),
    // 7. Operations & Docs
    'manifest.json': generateManifestJson({ domain: cleanDomain, siteName: name }),
    'structured-data-guide.md': generateStructuredDataGuide({ domain: cleanDomain, siteName: name }),
    'deployment-checklist.md': generateDeploymentChecklist({ domain: cleanDomain, siteName: name }),
    'README.md': generateReadmeDoc({ domain: cleanDomain, siteName: name })
  };

  const generated = [];
  for (const [relPath, content] of Object.entries(files)) {
    const filePath = path.join(targetDir, relPath);
    fs.writeFileSync(filePath, content, 'utf8');
    generated.push({ filename: relPath, filePath });
  }

  return { targetDir, files: generated };
}
