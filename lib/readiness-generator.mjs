export function generateAiSchema({ domain, siteName, description }) {
  return JSON.stringify({
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebSite",
        "@id": `https://${domain}/#website`,
        "url": `https://${domain}/`,
        "name": siteName,
        "description": description || `${siteName} official website.`,
        "publisher": {
          "@id": `https://${domain}/#organization`
        }
      },
      {
        "@type": "Organization",
        "@id": `https://${domain}/#organization`,
        "name": siteName,
        "url": `https://${domain}/`,
        "logo": `https://${domain}/assets/logo.png`
      }
    ]
  }, null, 2);
}

